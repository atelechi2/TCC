    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    
        
    boolean CicloPrincipal = true;    
    
    boolean entrouEmErro = false;
    String erro = "";    
   // String decomporSenha = TXSenha.getText();
    int max = TXSenha.getText().length();
    if(max==0)
        {
        erro = "senha sem nenhum caractere";
        entrouEmErro = true;
        }
    else
        {
    if (max < 8) 
        {
        erro = "Atenção!! Escolha outra senha(senha com poucos caracteres)";
        entrouEmErro = true;
        }
    else
        {
        int contadorDeNumeros = 0;
        int contadorDeLetras = 0;
        
       // String caractere[] = new String[max];
        String caractere = TXSenha.getText();
        for (int i = 0; i < max; i++) 
            {
            String car = caractere.substring(i, i+1);
            if (isInteger(car)) 
                {
                contadorDeNumeros++;
                }
            else
                {
                contadorDeLetras++;
                }
            }
            if (contadorDeNumeros < 3) 
                {
                erro = erro + "Escolha outra senha(senha com poucos numeros): "+contadorDeNumeros;
                entrouEmErro = true;
                }
            if (contadorDeLetras < 3) 
                {
                erro = erro +"Escolha outra senha(senha com poucas letras): "+contadorDeLetras;
                entrouEmErro = true;
                }
        }
        }
    if(entrouEmErro)
        {
        JOptionPane.showMessageDialog(null, erro);
        }
    else
        {
//************************************ Grava acao no banco **************************************************************
        //Grava acao no banco
        LogsBean entidadeAcao;
        UsuarioBean entidadeUsuario;
        entidadeAcao = new LogsBean();
        entidadeAcao.setId_Usuario(1);//Grava o usuario corrente
        //Pega a data corrente
        java.util.Date currentTime = new java.util.Date();
        entidadeAcao.setData(new java.sql.Timestamp(currentTime.getTime()));//new Date());
        entidadeAcao.setAcao(2);//ver qual opcao é gravar usuario no banco
        LogsDAO logAcao;
//************************************ Grava usuario no banco **************************************************************
        entidadeUsuario = new UsuarioBean();
        entidadeUsuario.setNome(TXNome.getText());//Grava o usuario corrente
        entidadeUsuario.setLogin(TXLogin.getText());
        entidadeUsuario.setSenha(TXSenha.getText());
        UsuarioDAO gravaUsuario;
        try 
            {
            logAcao = new JDBClogsDAO();
            logAcao.insereAcao(entidadeAcao);
            gravaUsuario = new JDBCusuarioDAO();
            gravaUsuario.insereUsuario(entidadeUsuario);
            listaUsuarios();
            TXLogin.setText("");
            TXNome.setText("");
            TXSenha.setText("");
            }
        catch (Exception ex) 
            {
            Logger.getLogger(VerificaLogs.class.getName()).log(Level.SEVERE, null, ex);
            }    
//**************************************************************************************************            
         JOptionPane.showMessageDialog(null, "Usuario arquivado");
         this.dispose();
        }
        
    }//GEN-LAST:event_jButton2ActionPerformed

