public void listaAcoes()
    {
     //Pega lista de acoes
        
        try 
            {
            
       
            }
        catch (Exception ex) 
            {
            Logger.getLogger(VerificaLogs.class.getName()).log(Level.SEVERE, null, ex);
            }
        
        
        
        //Listagem dos dados de log
         LogsDAO dados;
         UsuarioDAO usu;
         ListaAcaoDAO acoes;
        try 
            {
            acoes = new JDBClistaAcaoDAO();    
            usu = new JDBCusuarioDAO();
            dados = new JDBClogsDAO();
            List<ListaAcaoBean> listaAcoes = acoes.listaAcoes();
            List<UsuarioBean> listaUsu = usu.listaUsuarios();
            List<LogsBean> listaDados = dados.listaAcoes();
            String Buffer="        ID              Usuario                      Data / hora                                             Ação\n";
            Buffer = Buffer +"\n";
            for(int i = 0; i < listaDados.size(); i++)
                {
               
                Buffer = Buffer +"      "
                                +listaDados.get(i).getId()
                                +"             "
                                +listaUsu.get(listaDados.get(i).getId_Usuario()-1).getLogin()//Troca o ID pelo Nome do Usuario
                               // + listaDados.get(i).getId_Usuario()
                                +"                     "
                                +listaDados.get(i).getData()
                                +" / "
                                +listaDados.get(i).getDataHora()
                                +"                     "
                                +listaAcoes.get(listaDados.get(i).getListaacao_id()-1).getAcao()//Menos 1 para atingir a posição zero na lista

                                +"\n";
                areaDeTexto.setText(Buffer); 
                }  
            }
        catch (Exception ex) 
            {
            Logger.getLogger(VerificaLogs.class.getName()).log(Level.SEVERE, null, ex);
            }
    }
